function listSection({ cls, eyebrow, heading, items }) {
  if (!items || items.length === 0) return "";
  return `
<section class="${cls}"><div class="container two-col">
<div><p class="eyebrow">${esc(eyebrow.toUpperCase())}</p><h2>${esc(heading)}</h2></div>
<div class="service-list">
${items.map((it) => `<div><strong>${esc(it.title)}</strong>${it.text ? `<span>${esc(it.text)}</span>` : ""}</div>`).join("\n")}
</div></div></section>
`;
}

function paragraphs(text, cls) {
  return String(text).split(/\n\s*\n/).map((s) => s.trim()).filter(Boolean)
    .map((s) => `<p class="${cls}">${esc(s)}</p>`).join("\n");
}

export function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
