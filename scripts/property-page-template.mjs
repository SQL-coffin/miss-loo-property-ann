/* ==================== 房源详情页模板 ====================
   properties/<房源>/index.html 都由这个模板自动生成，
   资料来自同一个文件夹里的 listing.json（运营人员在 /admin/ 后台填写）。

   【想改所有房源详情页的版面 / 文字时，改这里】
   改完后运行 node scripts/build-properties.mjs，或推送到 GitHub 让 Action 自动运行。
   不要直接修改生成出来的 index.html，下次生成时会被覆盖。
   ============================================================ */

import { formatPrice, LISTING_TYPES } from "../js/domain/property.js";

export const GENERATED_MARKER = "<!-- GENERATED by scripts/build-properties.mjs — edit listing.json via /admin/, not this file -->";

const SITE_NAME = "Miss Loo JB Property";
const WHATSAPP_NUMBER = "60167889571";
const CSP = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'";

export function renderPropertyPage(p, { slug, siteUrl }) {
  const price = formatPrice(p);
  const listing = LISTING_TYPES[p.listingType];
  const pageUrl = `${siteUrl}properties/${slug}/`;
  const cover = p.photos[0];
  const whatsappUrl = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(
    p.whatsappMessage || `Hi Miss Loo, I'm interested in the ${p.title} (${p.location}) at ${price}.`
  )}`;
  const highlights = [p.tenure, p.bumiStatus, p.lotType, p.facing && `${p.facing} Facing`].filter(Boolean);
  const facts = [
    ["Property type", p.propertyTypeLabel],
    ["Land size", p.landSize],
    ["Built-up", p.builtUp],
    ["Bedrooms", p.bedrooms],
    ["Bathrooms", p.bathrooms],
    ["Tenure", p.tenure],
    ["Bumi status", p.bumiStatus],
    ["Lot", p.lotType],
    ["Facing", p.facing],
    ...(p.extraDetails || []).map((d) => [d.label, d.value]),
  ].filter(([, v]) => v !== undefined && v !== null && v !== "");

  const seoTitle = p.seo?.title || `${p.propertyTypeLabel || p.title} ${listing} in ${p.location} | ${price}`;
  const seoDescription = p.seo?.description || autoDescription(p, price, listing);
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "SingleFamilyResidence",
    name: `${p.title} — ${p.location}`,
    description: seoDescription,
    address: {
      "@type": "PostalAddress",
      streetAddress: p.address,
      addressLocality: p.city || "Johor Bahru",
      addressRegion: "Johor",
      addressCountry: "MY",
    },
    ...(p.bedrooms != null && { numberOfBedrooms: p.bedrooms }),
    ...(p.bathrooms != null && { numberOfBathroomsTotal: p.bathrooms }),
    offers: {
      "@type": "Offer",
      priceCurrency: "MYR",
      price: String(p.price),
      availability: "https://schema.org/InStock",
    },
  };

  return `<!doctype html>
<html lang="en">
<head>
${GENERATED_MARKER}
<meta charset="UTF-8">
<meta http-equiv="Content-Security-Policy" content="${CSP}">
<meta name="referrer" content="strict-origin-when-cross-origin">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(seoTitle)}</title>
<meta name="description" content="${esc(seoDescription)}">
<meta name="robots" content="index,follow">
<link rel="canonical" href="${esc(pageUrl)}">
<meta property="og:type" content="website">
<meta property="og:title" content="${esc(`${p.title} | ${price}`)}">
<meta property="og:description" content="${esc(seoDescription)}">
<meta property="og:url" content="${esc(pageUrl)}">
${cover ? `<meta property="og:image" content="${esc(pageUrl + cover.image)}">\n` : ""}<link rel="stylesheet" href="../../style.css"><link rel="icon" href="../../logo.jpg" type="image/jpeg">
<script type="application/ld+json">
${JSON.stringify(jsonLd).replace(/</g, "\\u003c")}
</script>
</head>
<body>
<header class="site-header"><div class="container nav">
<a class="brand" href="../../index.html"><img src="../../logo.jpg" alt="${SITE_NAME} logo"><span>MISS LOO JB PROPERTY</span></a>
<nav><a href="../../properties/">Properties</a><a href="../../buy-property/">Buy</a><a href="../../sell-property/">Sell</a><a href="../../rent-property/">Rent</a><a href="../../areas/">Areas</a><a class="nav-cta" href="https://wa.me/${WHATSAPP_NUMBER}" target="_blank" rel="noopener">WhatsApp</a></nav>
</div></header>
<main>
<section class="listing-hero"><div class="container">
<a class="back-link" href="../">← Back to properties</a>
<p class="eyebrow">${esc(`${listing} · ${p.areaLabel || p.area}`.toUpperCase())}</p>
<h1>${esc(p.title)}</h1>
<p class="listing-location">${esc(p.address)}</p>
<div class="price-row"><strong>${esc(price)}</strong>${highlights.length ? `<span>${highlights.map(esc).join(" · ")}</span>` : ""}</div>
<div class="hero-actions">
${p.facebookUrl ? `<a class="button primary" href="${esc(p.facebookUrl)}" target="_blank" rel="noopener">View Facebook Listing →</a>\n` : ""}<a class="button ${p.facebookUrl ? "secondary" : "primary"}" href="${esc(whatsappUrl)}" target="_blank" rel="noopener">WhatsApp Miss Loo</a>
</div>
</div></section>

<section class="section listing-section"><div class="container">
<div class="listing-gallery">
${p.photos.map((ph) => `<figure><img src="${esc(ph.image)}" alt="${esc(ph.alt || p.title)}">${ph.caption ? `<figcaption>${esc(ph.caption)}</figcaption>` : ""}</figure>`).join("\n")}
</div>
</div></section>

<section class="section soft"><div class="container listing-layout">
<div><p class="eyebrow">PROPERTY DETAILS</p><h2>${esc(p.detailsHeading || p.title)}</h2>
${p.description ? paragraphs(p.description, "listing-copy") : ""}
<div class="detail-grid">
${facts.map(([k, v]) => `<div><span>${esc(k)}</span><strong>${esc(v)}</strong></div>`).join("\n")}
</div></div>
<aside class="enquiry-card"><span class="card-kicker">INTERESTED?</span><h2>Arrange a viewing</h2><p>Contact Miss Loo for more details or to arrange a viewing.</p><a class="button primary" href="${esc(whatsappUrl)}" target="_blank" rel="noopener">WhatsApp Miss Loo</a><p class="agent-meta">REN: REN50378 · MW Properties</p></aside>
</div></section>
${listSection({ cls: "section", eyebrow: p.featuresLabel || "RENOVATION", heading: p.featuresHeading || "Features", items: p.features })}${listSection({ cls: "section soft", eyebrow: "LOCATION", heading: p.locationHeading || p.location, items: p.locationPoints })}${p.facebookUrl ? `
<section class="section social-listing-link"><div class="container contact-box"><div><p class="eyebrow">MORE PHOTOS & UPDATES</p><h2>See the original Facebook listing</h2><p>The Facebook post contains the latest photos, updates and listing information.</p></div><a class="button secondary" href="${esc(p.facebookUrl)}" target="_blank" rel="noopener">Open Facebook Post →</a></div></section>
` : ""}
<section class="section dark"><div class="container two-col"><div><p class="eyebrow">CONTACT</p><h2>Want to see the property?</h2></div><div><p>Miss Loo · MW Properties · REN50378</p><p>WhatsApp: +60 16-788 9571<br>Email: pohyuen0331@gmail.com</p><a class="button primary" href="https://wa.me/${WHATSAPP_NUMBER}" target="_blank" rel="noopener">Chat on WhatsApp</a></div></div></section>
</main>
<footer class="site-footer"><div class="container footer-inner"><span>© ${SITE_NAME}</span><span>${esc(p.location.split(/\s*,\s*/).join(" · "))}</span></div></footer>
</body></html>
`;
}

function listSection({ cls, eyebrow, heading, items }) {
  if (!items || items.length === 0) return "";
  return `
<section class="${cls}"><div class="container two-col">
<div><p class="eyebrow">${esc(eyebrow.toUpperCase())}</p><h2>${esc(heading)}</h2></div>
<div class="service-list">
${items.map((it) => `<div><strong>${esc(it.title)}</strong>${it.text ? `<span>${esc(it.text)}</span>` : ""}</div>`).join("\n")}
</div></div></section>
`;
}

function autoDescription(p, price, listing) {
  const bits = [
    p.landSize,
    p.bedrooms != null && `${p.bedrooms} bedrooms`,
    p.bathrooms != null && `${p.bathrooms} bathrooms`,
    p.tenure,
    p.bumiStatus,
  ].filter(Boolean);
  return `${p.title} ${listing.toLowerCase()} at ${p.address}. ${bits.join(", ")}. Asking ${price}.`;
}

function paragraphs(text, cls) {
  return String(text).split(/\n\s*\n/).map((t) => t.trim()).filter(Boolean)
    .map((t) => `<p class="${cls}">${esc(t)}</p>`).join("\n");
}

export function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
